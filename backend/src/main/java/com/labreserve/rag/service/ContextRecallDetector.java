package com.labreserve.rag.service;

import lombok.extern.slf4j.Slf4j;
import org.springframework.stereotype.Service;

import java.util.regex.Pattern;

/**
 * 上下文自省检测（R6）。
 *
 * <p>有一类问题<b>既不是知识库问题，也不是业务操作</b>，而是问"我们刚才聊了什么"：
 * <pre>
 *   我一开始问的是什么？
 *   我们前面讨论了哪些内容？
 *   你记得我刚才问了什么吗？
 *   总结一下我们前面聊的
 * </pre>
 *
 * <p>这类问题的答案<b>完全来自对话历史</b>，不需要检索知识库。
 * 若按普通 docs 流程走：
 * <ul>
 *   <li>检索这类问句必然不命中 → 被"检索未命中硬拒"拦掉；</li>
 *   <li>或被意图分类误判成 chitchat → 回一句"你好我是助手"，完全答非所问。</li>
 * </ul>
 *
 * <p>因此在进检索<b>之前</b>先做一次纯规则检测，命中就走
 * {@code ContextRecall} 分支：只把历史喂给 LLM，让它复述/概括本会话讨论过的内容，
 * <b>不检索、不产引用角标</b>。
 *
 * <h3>为什么用规则而不是 LLM 判断</h3>
 * 意图分类是 4 维固定（v3 收缩后），加第 5 维要动 {@code Intent} VO / 提示词 / 优先级链。
 * 而"问历史"这个特征在中文里句式很集中，用正则覆盖 95% 的情况足够，
 * 剩下 5% 漏掉也只是退回普通流程（硬拒），不会答错。
 */
@Slf4j
@Service
public class ContextRecallDetector {

    /**
     * 上下文自省问法。
     *
     * <p>分四类：
     * <ol>
     *   <li>问"我(一开始/最初/刚才/前面)问了什么"</li>
     *   <li>问"我们(前面/刚才/之前)(聊/讨论)了什么"</li>
     *   <li>问"你记得我(问/说)了什么吗"</li>
     *   <li>要求"总结/概括一下(我们)(前面/之前/刚才)的(讨论|对话|内容)"</li>
     * </ol>
     */
    private static final Pattern RECALL = Pattern.compile(
            // ① 我一开始/最初/刚才/前面 问了/说了 什么
            "我(一开始|最初|最早|刚才|前面|之前|先前|上次)(问|说)(的|了)?(是)?什么"
                    // ② 我们前面/刚才 聊/讨论 了什么
                    + "|(我们|咱们)(刚才|前面|之前|先前|一开始)?(聊|讨论|谈)(了)?(些|了)?(是)?什么"
                    // ②b 我们 + 过去时间词 + 问/说 + 什么
                    //    （时间词必需：否则"我们问的离心机注意事项"这种普通问题会被误判成回顾）
                    + "|(我们|咱们)(刚才|前面|之前|先前|一开始)(问|说)(的|了)?(是)?什么"
                    // ③ 我们(前面)讨论的(内容|话题)是什么
                    + "|(我们|咱们)(刚才|前面|之前|先前)?(讨论|聊|谈)(的|过)?(内容|话题|问题)(是|都)?什么"
                    // ④ 你记得我问了什么 / 我之前说过什么
                    + "|你(还)?(记得|记得我)(我)?(问|说)(过|了)?(是)?什么"
                    + "|我(之前|前面|刚才|先前)(跟|和)你(说|聊)(过|了)?(是)?什么"
                    // ⑥ 聊到哪了
                    + "|(我们|你)(现在)?(聊|说)到(哪|什么|哪儿)了"
                    + "|前面(说|聊|讲)到(哪|什么)"
                    // ⑦ 我问过什么
                    + "|我(问|说)(过|了)?(些|了)?什么"
                    , Pattern.CASE_INSENSITIVE);

    /**
     * 「总结/概括/回顾/复述/梳理 + 回顾语境词」句式。
     *
     * <p>单独拆一条规则而不是并进 {@link #RECALL}：这类句式的结构太松
     * （时间词、动词、"的"都可能缺，宾语还可能与动词同形，如"之前的讨论"），
     * 硬拼成一个正则会出现"改了 A 坏 B"的连锁反应（实测连续踩了 3 次）。
     * 拆开后语义清晰：<b>有回顾动词</b> + <b>邻近有回顾语境词</b>。
     *
     * <p>反例（不应命中）：「总结一下安全规章的要求」——
     * "要求"不在语境词表里，"安全规章的要求"里也没有"我们/刚才/内容/讨论"等词。
     */
    private static final Pattern RECALL_SUMMARY = Pattern.compile(
            "(总结|概括|回顾|复述|梳理|归纳)"
                    + "([^。？！]{0,12}?)"                       // 中间修饰，限长避免跨句
                    + "(我们|咱们|刚才|前面|之前|先前|对话|讨论|聊的|内容|问题)");

    /**
     * 判断问句是否在问"对话历史本身"。
     *
     * @param question 当前问句（重写后）
     * @return true = 走上下文回显分支
     */
    public boolean isRecall(String question) {
        if (question == null || question.isBlank()) {
            return false;
        }
        String text = question.trim();
        boolean hit = RECALL.matcher(text).find() || RECALL_SUMMARY.matcher(text).find();
        if (hit) {
            log.debug("[RAG][RECALL] 命中上下文自省问法: {}", question);
        }
        return hit;
    }
}
